'use strict';
// Faux OrcaSlicer pour les tests : mêmes arguments que le vrai (voir src/orca.js), écrit un petit gcode
// réaliste dans --outputdir. Le remplissage demandé choisit le scénario :
//   99 %  -> Orca échoue (code 1)       98 % -> pièces sur 2 plateaux (2 gcodes)
//   97 %  -> tué faute de mémoire (code 137)     95 % -> pièce hors du plateau (code 206)    sinon -> 1 gcode

const fs = require('node:fs');
const path = require('node:path');

const args = process.argv.slice(2);
const valeur = (nom) => args[args.indexOf(nom) + 1];
const [machine, process_] = valeur('--load-settings').split(';').map((f) => JSON.parse(fs.readFileSync(f, 'utf8')));
const sortie = valeur('--outputdir');
const options = new Set(['--arrange', '--orient', '--slice', '--load-settings', '--load-filaments', '--outputdir']);
const stls = args.filter((a, i) => !a.startsWith('--') && !options.has(args[i - 1]));

for (const f of stls) {
  const t = fs.readFileSync(f);
  if (t.length < 84) { console.error(`STL illisible : ${f}`); process.exit(2); }
}
if (!machine.printable_area || machine.thumbnails !== '') { console.error('profil machine inattendu'); process.exit(2); }

const remplissage = process_.sparse_infill_density;
if (remplissage === '99%') { console.error('[error] slicing failed: test'); process.exit(1); }
if (remplissage === '97%') { console.error('Killed'); process.exit(137); }      // tué par le système (mémoire)
if (remplissage === '95%') {                                                    // pièce hors du plateau une fois rangée
  console.error('plate 1: No object is fully inside the print volume. Arrange ran without rotations.'); process.exit(206);
}
if (remplissage === '96%') setTimeout(() => {}, 60e3);                          // très lent : arrêté en cours de route

// taille (x) de la première pièce reçue : vérifie la mise à l'échelle faite par le serveur
const premier = fs.readFileSync(stls[0]);
let xmin = Infinity, xmax = -Infinity;
if (premier.length === 84 + premier.readUInt32LE(80) * 50) {
  for (let i = 0; i < premier.readUInt32LE(80); i++) {
    for (let s = 0; s < 3; s++) { const x = premier.readFloatLE(84 + i * 50 + 12 + s * 12); xmin = Math.min(xmin, x); xmax = Math.max(xmax, x); }
  }
}
const couches = 3;
let g = `; generated by faux-orca\n; HEADER_BLOCK_START\n; total layer number: ${couches}\n; HEADER_BLOCK_END\n`
  + `; layer_height = ${process_.layer_height}\n; ironing_type = ${process_.ironing_type}\n; sparse_infill_density = ${remplissage}\n`
  + `; top_shell_layers = ${process_.top_shell_layers}\n; pieces = ${stls.length}\n; piece1_x = ${Math.round((xmax - xmin) * 100) / 100}\n`
  + `; orient = ${valeur('--orient')}\n; support_threshold_angle = ${process_.support_threshold_angle}\n`;
// comme le vrai Orca : un objet par exemplaire (nom du STL, contour sur le plateau), côte à côte
stls.forEach((f, i) => {
  const x = 30 + (i % 8) * 25, y = 30 + Math.floor(i / 8) * 25;
  g += `EXCLUDE_OBJECT_DEFINE NAME=${path.basename(f)}_id_${i}_copy_0 CENTER=${x},${y} POLYGON=[[${x - 10},${y - 10}],[${x + 10},${y - 10}],[${x + 10},${y + 10}],[${x - 10},${y + 10}]]\n`;
});
g += 'G90\nM83\n';
for (let c = 1; c <= couches; c++) {
  const z = (c * 0.2).toFixed(2);
  g += `;LAYER_CHANGE\nG1 Z${z} F600\nG0 X100 Y100\n;TYPE:Outer wall\n`
    + 'G1 X120 Y100 E1\nG1 X120 Y120 E1\nG1 X100 Y120 E1\nG1 X100 Y100 E1\n;TYPE:Sparse infill\nG1 X120 Y120 E1.4\n';
}
g += '; filament used [mm] = 4032.26\n; total filament weight [g] : 12.5\n; estimated printing time (normal mode) = 1h 2m 3s\n';

fs.writeFileSync(path.join(sortie, 'plate_1.gcode'), g);
if (remplissage === '98%') fs.writeFileSync(path.join(sortie, 'plate_2.gcode'), g);
